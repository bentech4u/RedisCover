# ============================================================ generic operator

def operator_install(spec: OperatorInstallSpec) -> list[dict]:
    """OperatorGroup + Subscription for any OperatorHub package.

    AllNamespaces installs into openshift-operators, which already has a
    cluster-wide OperatorGroup -- adding a second one there breaks every
    operator in that namespace, so we do not create one.
    """
    objs: list[dict] = []
    ns = spec.namespace

    if spec.install_mode != "AllNamespaces":
        objs.append({"apiVersion": "v1", "kind": "Namespace",
                     "metadata": {"name": ns, "labels": {"name": ns}}})
        targets = ([ns] if spec.install_mode == "OwnNamespace"
                   else [spec.target_namespace or ns])
        objs.append({
            "apiVersion": "operators.coreos.com/v1", "kind": "OperatorGroup",
            "metadata": {"name": f"{spec.package}-og", "namespace": ns},
            "spec": {"targetNamespaces": targets},
        })

    sub: dict[str, Any] = {
        "apiVersion": "operators.coreos.com/v1alpha1", "kind": "Subscription",
        "metadata": {"name": spec.package, "namespace": ns},
        "spec": {
            "channel": spec.channel,
            "name": spec.package,
            "source": spec.catalog_source,
            "sourceNamespace": "openshift-marketplace",
            "installPlanApproval": spec.approval,
        },
    }
    if spec.starting_csv:
        sub["spec"]["startingCSV"] = spec.starting_csv
    objs.append(sub)
    return objs


def enterprise_ui_route(spec: EnterpriseSpec) -> list[dict]:
    """Passthrough Route to the Redis Enterprise console.

    This works where a Route for Redis itself cannot: the console speaks HTTPS,
    so the browser sends TLS SNI and HAProxy can route on it without decrypting.
    `balance: source` is required -- the console keeps server-side session state
    across the REC pods, and without sticky sessions a login lands on one pod and
    the next request on another, which presents as a login that silently fails.
    """
    return [{
        "apiVersion": "route.openshift.io/v1", "kind": "Route",
        "metadata": {
            "name": f"{spec.rec_name}-ui",
            "namespace": spec.namespace,
            "annotations": {"haproxy.router.openshift.io/balance": "source"},
        },
        "spec": {
            "to": {"kind": "Service", "name": f"{spec.rec_name}-ui"},
            "port": {"targetPort": 8443},
            "tls": {"termination": "passthrough",
                    "insecureEdgeTerminationPolicy": "None"},
        },
    }]


def community_replication_manifests(spec: CommunitySpec, password: str) -> list[dict]:
    """Primary + replicas as a StatefulSet.

    `<name>-0` is the primary; every other ordinal starts with `replicaof <name>-0`.
    A StatefulSet is required because each pod needs a stable name (the replicas
    address the primary by DNS) and its own PVC.

    NO AUTOMATIC FAILOVER. If <name>-0 dies, Kubernetes restarts it and the
    replicas reconnect -- but nothing promotes a replica in the meantime. This is
    read scaling and a warm standby. For real HA use Sentinel via the operator.
    """
    v = community_version(spec.version_id) or {}
    image = spec.custom_image or v.get("image") or "docker.io/redis:7.4-alpine"
    name, ns = spec.name, spec.namespace
    headless = f"{name}-headless"
    labels = {"app": name, "app.kubernetes.io/name": name,
              "app.kubernetes.io/managed-by": "redis-deployer",
              "redis-deployer/topology": "replication"}

    # entrypoint: ordinal 0 is the primary, everyone else replicates from it
    boot = (
        'ORD="${HOSTNAME##*-}"\n'
        'CONF=/tmp/redis.conf\n'
        'cp /etc/redis/redis.conf "$CONF"\n'
        'if [ "$ORD" != "0" ]; then\n'
        f'  echo "replicaof {name}-0.{headless}.{ns}.svc 6379" >> "$CONF"\n'
        '  echo "replica-read-only yes" >> "$CONF"\n'
        'fi\n'
        'if [ -n "$REDIS_PASSWORD" ]; then\n'
        '  echo "requirepass $REDIS_PASSWORD" >> "$CONF"\n'
        '  echo "masterauth $REDIS_PASSWORD" >> "$CONF"\n'
        'fi\n'
        'exec redis-server "$CONF"\n'
    )

    env = []
    if spec.auth_enabled:
        env.append({"name": "REDIS_PASSWORD", "valueFrom": {
            "secretKeyRef": {"name": f"{name}-auth", "key": "redis-password"}}})
        ready = 'redis-cli -a "$REDIS_PASSWORD" --no-auth-warning ping | grep -q PONG'
    else:
        ready = "redis-cli ping | grep -q PONG"

    objs: list[dict] = [
        {"apiVersion": "v1", "kind": "Namespace",
         "metadata": {"name": ns, "labels": {"name": ns}}},
        {"apiVersion": "v1", "kind": "ConfigMap",
         "metadata": {"name": f"{name}-config", "namespace": ns, "labels": labels},
         "data": {"redis.conf": redis_conf(spec)}},
    ]
    if spec.auth_enabled:
        objs.append({
            "apiVersion": "v1", "kind": "Secret",
            "metadata": {"name": f"{name}-auth", "namespace": ns, "labels": labels},
            "type": "Opaque",
            "data": {"redis-password": base64.b64encode(password.encode()).decode()},
        })

    # headless service: gives every pod a stable DNS name for peer discovery
    objs.append({
        "apiVersion": "v1", "kind": "Service",
        "metadata": {"name": headless, "namespace": ns, "labels": labels},
        "spec": {"clusterIP": "None", "selector": {"app": name},
                 "publishNotReadyAddresses": True,
                 "ports": [{"name": "redis", "port": 6379, "targetPort": 6379}]},
    })

    sts: dict[str, Any] = {
        "apiVersion": "apps/v1", "kind": "StatefulSet",
        "metadata": {"name": name, "namespace": ns, "labels": labels},
        "spec": {
            "serviceName": headless,
            "replicas": max(2, spec.replicas),
            "podManagementPolicy": "OrderedReady",   # the primary must exist first
            "selector": {"matchLabels": {"app": name}},
            "template": {
                "metadata": {"labels": labels},
                "spec": {
                    "securityContext": {"runAsNonRoot": True,
                                        "seccompProfile": {"type": "RuntimeDefault"}},
                    "affinity": {"podAntiAffinity": {
                        "preferredDuringSchedulingIgnoredDuringExecution": [{
                            "weight": 100,
                            "podAffinityTerm": {
                                "topologyKey": "kubernetes.io/hostname",
                                "labelSelector": {"matchLabels": {"app": name}}},
                        }]}},
                    "containers": [{
                        "name": "redis",
                        "image": image,
                        "imagePullPolicy": "IfNotPresent",
                        "command": ["sh", "-c", boot],
                        "env": env,
                        "ports": [{"name": "redis", "containerPort": 6379}],
                        "securityContext": {"allowPrivilegeEscalation": False,
                                            "capabilities": {"drop": ["ALL"]}},
                        "resources": {
                            "requests": {"cpu": spec.cpu_request,
                                         "memory": spec.memory_request},
                            "limits": {"cpu": spec.cpu_limit,
                                       "memory": spec.memory_limit}},
                        "volumeMounts": [
                            {"name": "data", "mountPath": "/data"},
                            {"name": "config", "mountPath": "/etc/redis", "readOnly": True}],
                        "startupProbe": {"tcpSocket": {"port": 6379},
                                         "periodSeconds": 5, "failureThreshold": 30},
                        "readinessProbe": {"exec": {"command": ["sh", "-c", ready]},
                                           "periodSeconds": 10, "timeoutSeconds": 3},
                        "livenessProbe": {"tcpSocket": {"port": 6379},
                                          "periodSeconds": 15, "failureThreshold": 3},
                    }],
                    "volumes": [{"name": "config",
                                 "configMap": {"name": f"{name}-config"}}],
                },
            },
        },
    }
    if not env:
        sts["spec"]["template"]["spec"]["containers"][0].pop("env")

    if spec.persistence != "none":
        claim: dict[str, Any] = {
            "metadata": {"name": "data"},
            "spec": {"accessModes": ["ReadWriteOnce"],
                     "resources": {"requests": {"storage": spec.storage_size}}},
        }
        if spec.storage_class:
            claim["spec"]["storageClassName"] = spec.storage_class
        sts["spec"]["volumeClaimTemplates"] = [claim]
    else:
        sts["spec"]["template"]["spec"]["volumes"].append(
            {"name": "data", "emptyDir": {}})
    objs.append(sts)

    # one Service for writes (primary only), one for reads (everything)
    objs.append({
        "apiVersion": "v1", "kind": "Service",
        "metadata": {"name": name, "namespace": ns, "labels": labels,
                     "annotations": {"redis-deployer/role": "primary (writes)"}},
        "spec": {"type": spec.service_type, "selector": {
            "app": name, "statefulset.kubernetes.io/pod-name": f"{name}-0"},
            "ports": [{"name": "redis", "port": 6379, "targetPort": 6379}]},
    })
    objs.append({
        "apiVersion": "v1", "kind": "Service",
        "metadata": {"name": f"{name}-read", "namespace": ns, "labels": labels,
                     "annotations": {"redis-deployer/role": "all pods (reads)"}},
        "spec": {"type": "ClusterIP", "selector": {"app": name},
                 "ports": [{"name": "redis", "port": 6379, "targetPort": 6379}]},
    })

    if spec.allow_namespaces:
        objs.append(network_policy(ns, {"app": name}, 6379, spec.allow_namespaces,
                                   f"allow-clients-to-{name}"))
    return objs
